"""Build web/mocks/data.js from REAL API responses (the FastAPI app driving the engine and scenario generator).

    .venv/bin/python web/mocks/build_mock_data.py

Nothing here is hand-typed: every number in the mocks comes from these responses. Buy lists are trimmed to
the first few rows (counts stay as reported) to keep the file small.
"""

import json
import pathlib

from fastapi.testclient import TestClient

from roundup_api.main import create_app

OUT = pathlib.Path(__file__).resolve().parent / "data.js"
c = TestClient(create_app(rate_limits={"simulate": 1000, "compare": 1000}))


def post(path, body):
    r = c.post(path, json=body)
    assert r.status_code == 200, r.text
    return r.json()


def trim(result):
    result = dict(result)
    result["buys_preview"] = result.pop("buys")[:5]
    return result


BASE = {"scenario_id": "crash-and-recovery", "style": "broad", "start": "2015-01-02", "end": "2024-12-31",
        "generate": {"seed": 42, "max_per_day": 2}}

results = post("/v1/simulate", dict(BASE, strategy="threshold", reinvest=True))
results["result"] = trim(results["result"])
short = post("/v1/simulate", dict(BASE, start="2020-01-02", end="2020-12-31", strategy="threshold", reinvest=True))
short["result"] = trim(short["result"])
compare = post("/v1/compare", dict(BASE, a={"strategy": "threshold", "reinvest": True},
                                   b={"strategy": "monthly", "reinvest": False}))
compare["a"], compare["b"] = trim(compare["a"]), trim(compare["b"])

saved = []
for name, sid, style, strategy, reinvest in [("Coffee money, crash test", "crash-and-recovery", "broad", "threshold", True),
                                             ("Weekly vs dividends", "steady-growth", "dividend", "weekly", True),
                                             ("No reinvesting", "sideways", "broad", "monthly", False)]:
    r = post("/v1/simulate", dict(BASE, scenario_id=sid, style=style, strategy=strategy, reinvest=reinvest))
    saved.append({"name": name, "scenario_id": sid, "style": style, "strategy": strategy, "reinvest": reinvest,
                  "summary": r["result"]["summary"], "meta": r["meta"]})

data = {"scenarios": c.get("/v1/scenarios").json(), "assumptions": c.get("/v1/assumptions").json(),
        "results": results, "short_results": short, "compare": compare, "saved": saved,
        "request": BASE}
OUT.write_text("// Generated by build_mock_data.py from real API responses. Do not edit by hand.\n"
               "window.ROUNDUP_MOCK = " + json.dumps(data, indent=1) + ";\n")
print(f"wrote {OUT} ({OUT.stat().st_size // 1024} KB)")
