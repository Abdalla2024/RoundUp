"""Guard for the two ways this repository's Python dependencies are installed (stage 6: CI broke when the Vercel form
`roundup-engine @ ./engine` reached pip, which rejects it: "Invalid URL './engine': No scheme supplied").

  requirements.txt      read by VERCEL (its uv installer). The two local packages are written `name @ ./path`, because the bare
                        `./engine` form failed there ("Package metadata name roundup-engine does not match given name engine").
  requirements-ci.txt   read by PIP (CI and local setup). Same pins; the two local packages are written `./engine`, `./api`,
                        the form pip accepts. It is DERIVED from requirements.txt by this script, so the pins cannot drift.

    python tools/check_requirements.py            # run the checks (what CI runs)
    python tools/check_requirements.py --write    # regenerate requirements-ci.txt after editing requirements.txt

The checks: (1) requirements-ci.txt equals what the script derives; (2) requirements.txt keeps the known-good Vercel lines;
(3) a fresh virtual environment installs with EXACTLY the command CI uses (python -m venv, then pip install -r
requirements-ci.txt -r requirements-test.txt) and the API imports and answers; (4) if uv is installed, the Vercel file installs
with uv in a fresh environment. What this cannot prove: that Vercel's own build accepts requirements.txt (only a deployment
does; the form here is the one that built on 2026-10-13).
"""

import pathlib
import re
import shutil
import subprocess
import sys
import tempfile

ROOT = pathlib.Path(__file__).resolve().parent.parent
VERCEL_LINES = ["roundup-engine @ ./engine", "roundup-api @ ./api"]          # known to build on Vercel
PIP_LINES = ["./engine", "./api"]
HEADER = ("# GENERATED by tools/check_requirements.py --write from requirements.txt. Do not edit by hand.\n"
          "# For pip (CI, local setup). Vercel reads requirements.txt, where the local packages are written 'name @ ./path'.\n")


def derive(vercel_text: str) -> str:
    lines = vercel_text.splitlines()
    out = []
    for line in lines:
        out.append(PIP_LINES[VERCEL_LINES.index(line)] if line in VERCEL_LINES else line)
    return HEADER + "\n".join(out) + "\n"


def run(cmd, **kw):
    return subprocess.run(cmd, capture_output=True, text=True, **kw)


def pip_accepts(requirements_files: list[pathlib.Path], python=sys.executable) -> tuple[bool, str]:
    """Does pip accept these requirement files? Dry run: parses everything and resolves, installs nothing."""
    cmd = [python, "-m", "pip", "install", "--dry-run", "--no-deps", "--disable-pip-version-check"]
    for f in requirements_files:
        cmd += ["-r", str(f)]
    r = run(cmd, cwd=ROOT)
    return r.returncode == 0, (r.stdout + r.stderr)[-600:]


def main(write: bool) -> int:
    vercel = (ROOT / "requirements.txt").read_text()
    ci_file = ROOT / "requirements-ci.txt"
    if write:
        ci_file.write_text(derive(vercel))
        print("wrote requirements-ci.txt")
        return 0
    problems = []
    if not all(l in vercel.splitlines() for l in VERCEL_LINES):
        problems.append(f"requirements.txt must keep the Vercel lines {VERCEL_LINES}")
    if not ci_file.exists() or ci_file.read_text() != derive(vercel):
        problems.append("requirements-ci.txt is out of date: run python tools/check_requirements.py --write")
    if re.search(r"^\./", vercel, re.M):
        problems.append("requirements.txt has a bare './path' line (Vercel's uv rejects it)")
    if re.search(r"^\S+ @ \./", ci_file.read_text() if ci_file.exists() else "", re.M):
        problems.append("requirements-ci.txt has a 'name @ ./path' line (pip rejects it)")
    if problems:
        print("\n".join("FAIL: " + p for p in problems)); return 1

    # (3) the exact CI install, in a fresh virtual environment
    with tempfile.TemporaryDirectory() as tmp:
        venv = pathlib.Path(tmp) / ".venv"
        print(f"python {sys.version.split()[0]}; creating a fresh venv and running the CI command", flush=True)
        r = run([sys.executable, "-m", "venv", str(venv)]); assert r.returncode == 0, r.stderr
        py, pip = venv / "bin" / "python", venv / "bin" / "pip"
        print("pip", run([str(pip), "--version"]).stdout.strip())
        r = run([str(pip), "install", "-r", "requirements-ci.txt", "-r", "requirements-test.txt"], cwd=ROOT)
        if r.returncode != 0:
            print("FAIL: pip could not install from requirements-ci.txt\n" + (r.stdout + r.stderr)[-1500:]); return 1
        r = run([str(py), "-c", "import roundup_api, roundup_engine, roundup_scenarios, sys; "
                 "from roundup_api.main import app; from fastapi.testclient import TestClient; "
                 "print(TestClient(app).get('/v1/health').json()['status'])"], cwd=tmp)
        if r.returncode != 0 or "ok" not in r.stdout:
            print("FAIL: the installed API does not start\n" + (r.stdout + r.stderr)[-800:]); return 1
        print("pip path OK: installed and /v1/health is", r.stdout.strip().splitlines()[-1])

    # (4) the Vercel file with uv, when uv is available
    uv = shutil.which("uv")
    if uv:
        with tempfile.TemporaryDirectory() as tmp:
            run([uv, "venv", "-q", f"{tmp}/.v"])
            r = run([uv, "pip", "install", "-q", "--python", f"{tmp}/.v/bin/python", "-r", "requirements.txt"], cwd=ROOT)
            if r.returncode != 0:
                print("FAIL: uv could not install from requirements.txt\n" + (r.stdout + r.stderr)[-1200:]); return 1
            print("uv path OK: requirements.txt installs with uv")
    else:
        print("uv not installed: skipped the uv check")
    return 0


if __name__ == "__main__":
    sys.exit(main("--write" in sys.argv))
